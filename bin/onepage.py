#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Compose the built role pages into ONE scrolling document with anchor navigation.

Why this exists: six files means six loads, six back-buttons, and a reader on a
show floor losing their place. One document with anchors keeps the whole pack in
one scroll and one Ctrl-F.

What it does NOT change: the roles. Each role is still generated by its own
writer into its own fragment; this step only concatenates the built output and
rewrites cross-page links into in-page anchors. One writer per role still holds
(RULES B12) — nothing here authors content.

Reads  <ROOT>/docs/*.html            (already built, already gated)
Writes <ROOT>/deliverables/<slug>-onepage.html

NOT into docs/: qa-gate counts pages in docs/ against STATE.pages[], so a seventh
file there turns every build into 6/7. This is a derived VIEW of the six role
pages, not a seventh page. 〔Ray-Summit-2026〕

ROOT is a literal written by scaffold.sh. RULES B9: never from argv, never CWD.
"""

import io
import json
import os
import re
import sys

ROOT = '/Volumes/ClaudeNVME/26082426-RAY-SUMMIT'
DOCS = os.path.join(ROOT, 'docs')
STATE_P = os.path.join(ROOT, 'STATE.json')

# role -> (file, anchor id). Order is the reading order, not the file order.
ORDER = [
    ('command-center', 'index.html',     'war-room'),
    ('agenda',         'agenda.html',    'agenda'),
    ('gtm',            'gtm.html',       'plays'),
    ('accounts',       'accounts.html',  'accounts'),
    ('compare',        'compare.html',   'matchup'),
]

state = json.load(io.open(STATE_P, encoding='utf-8'))
camp = state.get('campaign', {})
slug = os.path.basename(ROOT.rstrip('/')).lower()


def read(fn):
    p = os.path.join(DOCS, fn)
    if not os.path.exists(p):
        sys.exit('onepage: FAIL missing %s — run make.sh all first' % p)
    return io.open(p, encoding='utf-8').read()


def grab(pat, text, what, fn):
    m = re.search(pat, text, re.S)
    if not m:
        sys.exit('onepage: FAIL could not find %s in %s' % (what, fn))
    return m.group(1)


base = read('index.html')
style = grab(r'<style[^>]*>(.*?)</style>', base, '<style>', 'index.html')
script = grab(r'<script[^>]*>(.*?)</script>', base, '<script>', 'index.html')
header = grab(r'(<header[^>]*>.*?</header>)', base, '<header>', 'index.html')

# --- section bodies -------------------------------------------------------
sections = []
for role, fn, anchor in ORDER:
    t = read(fn)
    body = grab(r'<main[^>]*>(.*?)</main>', t, '<main>', fn)
    # the per-page nav is replaced by one document-level nav
    body = re.sub(r'<nav\b[^>]*class="nav"[^>]*>.*?</nav>', '', body, flags=re.S)
    # Cross-page links become in-page anchors. The DEEP form must be rewritten
    # FIRST: "accounts.html#acct-lambda" carries its own fragment and only needs
    # the filename stripped, whereas "accounts.html" needs the section anchor
    # appended. Doing the bare form first turns the deep form into
    # "#accounts#acct-lambda", and doing only the bare form leaves the deep one
    # pointing at a file that does not exist in a single-document edition.
    # 〔Ray-Summit-2026: 323 dead cross-references shipped in the folded edition〕
    for _r, f2, a2 in ORDER:
        body = body.replace('href="%s#' % f2, 'href="#')
    for _r, f2, a2 in ORDER:
        body = body.replace('href="%s"' % f2, 'href="#%s"' % a2)
    sections.append((role, anchor, body))

# --- one document-level nav ----------------------------------------------
LABELS = {
    'war-room': ('作戰台', 'War Room'), 'agenda': ('議程', 'Agenda'),
    'plays': ('打法', 'Plays'), 'accounts': ('帳戶板', 'Accounts'),
    'matchup': ('對位', 'Matchup'),
}
nav_items = '\n'.join(
    '    <li><a href="#%s"><span data-t="h">%s</span><span data-t="e">%s</span></a></li>'
    % (a, LABELS[a][0], LABELS[a][1]) for _r, a, _b in sections)
nav = ('<nav class="nav navstick" data-block="nav" aria-label="Sections / 章節">\n'
       '  <ul>\n%s\n  </ul>\n</nav>' % nav_items)

body_html = '\n'.join(
    '<section id="%s" class="onepage-sec" data-role="%s" tabindex="-1">\n%s\n</section>'
    % (a, r, b) for r, a, b in sections)

extra = """
/* onepage additions — sticky section nav, section rules, print */
.navstick{position:sticky;top:0;z-index:50;backdrop-filter:saturate(1.4) blur(8px)}
.onepage-sec{scroll-margin-top:4.5rem}
.onepage-sec + .onepage-sec{border-top:1px solid var(--line,#e4e0d7);margin-top:3.5rem;padding-top:2.5rem}
.totop{position:fixed;right:1rem;bottom:1rem;z-index:60;min-width:44px;min-height:44px;
  display:inline-flex;align-items:center;justify-content:center;border-radius:999px;
  border:1px solid var(--line,#e4e0d7);background:var(--card,#fff);color:var(--ink,#15181d);
  text-decoration:none;font-size:15px;box-shadow:0 1px 3px rgba(0,0,0,.12)}
@media print{.navstick,.totop{display:none}.onepage-sec{break-before:page}}
@media (prefers-reduced-motion:no-preference){html{scroll-behavior:smooth}}
"""

title_h = '%s 情報包' % camp.get('event', '')
title_e = '%s intelligence pack' % camp.get('event', '')

# RULES A1/D1: charset MUST land inside the browser's 1024-byte pre-scan window,
# so it is the FIRST thing in the file — before <title>, which carries CJK itself.
# 〔AMD-2026 mojibake; Ray-Summit-2026 shipped one build without it〕
out = """<meta charset="utf-8">
<title>%s</title>
<meta name="viewport" content="width=device-width,initial-scale=1">
<style>%s%s</style>
%s
%s
<main class="wrap">
%s
</main>
<a class="totop" href="#top" aria-label="Back to top / 回到頂端">&#8593;</a>
<script>%s</script>
""" % (title_h, style, extra, header.replace('<header', '<header id="top"', 1),
       nav, body_html, script)

dst = os.path.join(ROOT, 'deliverables', '%s-onepage.html' % slug)
io.open(dst, 'w', encoding='utf-8').write(out)

# mechanical self-checks — these mirror qa-gate so a bad compose fails here
problems = []
if 'charset' not in out[:1024]:
    problems.append('charset not inside the 1024-byte pre-scan window (RULES A1/D1)')
if 'innerHTML' in out:
    problems.append('innerHTML present (RULES A2)')
if re.search(r'src="https?://|<link[^>]+href="https?://|@import\s+url\(\s*["\']?https?:', out):
    problems.append('external resource referenced (RULES A3)')
for _r, _f, a in ORDER:
    if 'id="%s"' % a not in out:
        problems.append('anchor #%s missing' % a)
# Every href in a folded document is same-document. One that still names a file
# is a link to nothing — and it LOOKS fine until someone clicks it.
_dead = re.findall(r'href="([A-Za-z0-9_-]+\.html#[^"]*)"', out)
if _dead:
    problems.append('%d cross-page link(s) survived the fold, e.g. %s — these are dead in a '
                    'single-document edition' % (len(_dead), ', '.join(sorted(set(_dead))[:3])))
# Every in-page href must have a target in this document.
_targets = set(re.findall(r'\sid="([^"]+)"', out))
_miss = sorted({f for f in re.findall(r'href="#([^"]+)"', out) if f and f not in _targets})
if _miss:
    problems.append('%d in-page link(s) point at an id this document does not contain: %s'
                    % (len(_miss), ', '.join(_miss[:5])))
if out.count('data-t="e"') < 6:
    problems.append('EN strings missing — the toggle would have nothing to show')
if problems:
    sys.exit('onepage: FAIL\n  ' + '\n  '.join(problems))

print('onepage: %s (%d KB) — %d sections, anchors %s'
      % (os.path.basename(dst), len(out.encode('utf-8')) // 1024,
         len(sections), ' '.join('#' + a for _r, _f, a in ORDER)))
