#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""build_views.py — make.sh step 2. Regenerate the generated views FROM the JSON.

RULES D2: the JSON catalogs are the factbase. A markdown list is a GENERATED
VIEW and loses every argument it has with the JSON. So this script never reads
the old view, never merges, never patches: it truncates and rewrites
deliverables/NN-sessions-list.md from data/sessions.json every single time.

If a human edited the view, that edit is gone — by design. The fix is to edit
the JSON and run `make.sh views`, which is exactly what check_facts F5 tells
anyone who tries.

Counts in the header are COMPUTED here (B16). Where the catalogue exposes
nothing, the cell says GAP and why (B13) — never 0, never 無, never a dash.

ROOT is a literal written by scaffold.sh (RULES B9).
"""
ROOT = '/Volumes/ClaudeNVME/26082426-RAY-SUMMIT'

import io
import json
import os
import sys

DATA = os.path.join(ROOT, 'data')
DELIV = os.path.join(ROOT, 'deliverables')
STATE_P = os.path.join(ROOT, 'STATE.json')
VIEW = os.path.join(DELIV, '01-sessions-list.md')   # NN-<view>.md, generated


def load(path, default=None):
    try:
        return json.load(io.open(path, encoding='utf-8'))
    except FileNotFoundError:
        return default


def cell(v):
    """A markdown cell. Never emit an absence token — check_facts F3 rejects
    無 / N/A / — and it is right to: an empty cell is a gap, not a finding."""
    if v is None or (isinstance(v, str) and not v.strip()):
        return ''
    return str(v).replace('|', '\\|').replace('\n', ' ').strip()


def main():
    state = load(STATE_P) or {}
    campaign = state.get('campaign') or {}
    factbase = state.get('factbase') or {}
    sessions = load(os.path.join(DATA, 'sessions.json'), []) or []
    if isinstance(sessions, dict):
        sessions = sessions.get('items') or sessions.get('records') or []
    if not isinstance(sessions, list):
        sys.exit('build_views: FAIL data/sessions.json is not a list of records')

    asof = factbase.get('asOf') or ''
    source = factbase.get('source') or campaign.get('catalog') or ''

    # ---------------------------------------------------- computed counts ---
    by_day = {}
    by_room = {}
    by_tag = {}
    seats_known = 0
    for s in sessions:
        by_day[str(s.get('day') or '')] = by_day.get(str(s.get('day') or ''), 0) + 1
        by_room[str(s.get('room') or '')] = by_room.get(str(s.get('room') or ''), 0) + 1
        for t in (s.get('tags') or []):
            by_tag[str(t)] = by_tag.get(str(t), 0) + 1
        if s.get('seats') not in (None, ''):
            seats_known += 1

    out = []
    w = out.append
    w('# %s — 場次總表（生成檔）' % (campaign.get('event') or 'event'))
    w('')
    w('> 這個檔案由 `make.sh views` 從 `data/sessions.json` 重新生成。**不要手改**：')
    w('> 下一次建置會整份覆蓋。要改內容就改 JSON（RULES D2 —— JSON 贏，view 是產物）。')
    w('')
    w('- 來源：%s' % (source or 'GAP —— STATE.factbase.source 未設定'))
    w('- 狀態截至：%s' % (asof or 'GAP —— STATE.factbase.asOf 未設定'))
    w('- 場次總數（計算值）：%d' % len(sessions))
    for d in sorted(by_day):
        w('  - %s：%d 場' % (d or 'GAP —— 記錄未帶日期', by_day[d]))
    if by_tag:
        w('- 主題標籤（計算值）：' + '、'.join('%s %d' % (k, by_tag[k])
                                          for k in sorted(by_tag, key=lambda x: (-by_tag[x], x))))
    w('- 會議室（計算值）：%d 間' % len([r for r in by_room if r]))
    if seats_known == 0:
        w('- 座位數：GAP —— 官方目錄沒有揭露任何一場的容量；未揭露不等於沒有座位（B13）')
    else:
        w('- 座位數：%d / %d 場有揭露' % (seats_known, len(sessions)))
    w('')
    w('| id | day | start_end | room | title | tags | seats |')
    w('| --- | --- | --- | --- | --- | --- | --- |')
    for s in sessions:
        seats = s.get('seats')
        seats_cell = cell(seats) if seats not in (None, '') else 'GAP（%s）' % (
            cell(s.get('seats_note')) or '目錄未揭露容量')
        w('| %s | %s | %s | %s | %s | %s | %s |' % (
            cell(s.get('id')),
            cell(s.get('day')),
            cell(s.get('start_end') or s.get('start')),
            cell(s.get('room')),
            cell(s.get('title')),
            cell('、'.join(str(t) for t in (s.get('tags') or []))) or 'GAP（目錄未給標籤）',
            seats_cell))
    w('')
    gaps = factbase.get('gaps') or []
    if gaps:
        w('## 已登記的缺口（STATE.factbase.gaps）')
        w('')
        for g in gaps:
            w('- GAP —— %s' % g)
        w('')
    w('<!-- generated by bin/build_views.py from data/sessions.json — do not hand-edit -->')

    if not os.path.isdir(DELIV):
        os.makedirs(DELIV)
    io.open(VIEW, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    print('build_views: rewrote %s from data/sessions.json (%d sessions, %d days)'
          % (os.path.relpath(VIEW, ROOT), len(sessions), len([d for d in by_day if d])))


main()
